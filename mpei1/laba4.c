/*
    laba4.c
    Программа считывает из файла input.txt целое n, затем два массива X и Y длины n,
    выводит считанные массивы в output.txt и вычисляет сумму и количество положительных
    элементов X[i], для которых выполняется X[i] > Y[i].

    Комментарии в коде поясняют логику и указывают на потенциальные места для улучшения.
*/

#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>

int laba4() {
    /* Открываем файл для чтения входных данных */
    FILE* fin = fopen("input.txt", "r");
    if (fin == NULL) {
        /* Если открыть input.txt не удалось, perror печатает сообщение об ошибке в stderr.
           В текущей реализации функция продолжит работу, но это опасно: дальнейшие
           вызовы fscanf и fclose с fin == NULL приведут к неопределённому поведению.
           Лучше сразу вернуть ненулевой код ошибки после закрытия уже открытых ресурсов.
        */
        perror("Cannot open input.txt");
        /* Рекомендуем: return 1; */
    }

    /* Открываем файл для вывода результата */
    FILE* fout = fopen("output.txt", "w");
    if (fout == NULL) {
        /* Если output.txt не открылся, perror сообщает об ошибке.
           Здесь код пытается закрыть fin, но затем продолжает работу — это тоже риск.
           Правильнее: закрыть fin (если он открыт) и вернуть код ошибки.
        */
        perror("Cannot open output.txt");
        fclose(fin); /* Закрываем только если fin != NULL, но текущая реализация не проверяет. */
        /* Рекомендуем: return 1; */
    }

    int n;
    int count = 0; /* количество подходящих элементов */
    int sum = 0;   /* сумма подходящих элементов */
    int X[20];     /* фиксированный буфер для массива X (макс 20 элементов) */
    int Y[20];     /* фиксированный буфер для массива Y (макс 20 элементов) */

    /* Читаем длину массивов n из входного файла
       Проверяем возвращаемое значение fscanf: он возвращает количество успешно считанных
       элементов, поэтому сравниваем с 1 (ожидаем одно целое число). */
    if (fscanf(fin, "%d", &n) != 1) {
        /* Пишем сообщение об ошибке во выходной файл. В реальной программе полезно
           также писать диагностические сообщения в stderr и завершать функцию с ошибкой. */
        fprintf(fout, "Error: cannot read array length\n");
    }
    else if (n < 1 || n > 20) {
        /* Проверяем допустимый диапазон n. Так как массивы объявлены как length 20,
           n вне диапазона приведёт к выходу за границы при чтении/записи. */
        fprintf(fout, "Error, because array length is not acceptable\n");
    }
    else {
        /* Флаг ok показывает, были ли прочитаны все ожидаемые числа */
        int ok = 1;
        for (int i = 0; i < n && ok; i++) {
            /* Читаем элементы массива X; если чтение прекратилось, устанавливаем ok=0 */
            if (fscanf(fin, "%d", &X[i]) != 1) ok = 0;
        }
        for (int i = 0; i < n && ok; i++) {
            /* Читаем элементы массива Y; опять же проверяем успех чтения */
            if (fscanf(fin, "%d", &Y[i]) != 1) ok = 0;
        }

        if (!ok) {
            /* Если данных было недостаточно, сообщаем об этом в выходной файл */
            fprintf(fout, "Error: not enough data in input file\n");
        }
        else {
            /* Выводим прочитанные данные в выходной файл для наглядности */
            fprintf(fout, "n = %d\n", n);
            fprintf(fout, "--- Array X ---\n");
            for (int i = 0; i < n; i++) {
                fprintf(fout, "%d\n", X[i]);
            }
            fprintf(fout, "--- Array Y ---\n");
            for (int i = 0; i < n; i++) {
                fprintf(fout, "%d\n", Y[i]);
            }

            /* Основной алгоритм:
               Проходим по индексам, и для каждого i, где X[i] > Y[i] и X[i] > 0,
               увеличиваем счётчик и добавляем X[i] к сумме. */
            for (int i = 0; i < n; i++) {
                if (X[i] > Y[i] && X[i] > 0) {
                    count++;
                    sum += X[i];
                }
            }

            if (count > 0) {
                fprintf(fout, "Your result:\nSum: %d\nCount: %d\n", sum, count);
            }
            else {
                fprintf(fout, "There are no such elements in the array\n");
            }
        }
    }

    /* Закрываем файлы. В более безопасной реализации нужно проверять, что дескрипторы
       fin и fout не равны NULL перед вызовом fclose. */
    fclose(fin);
    fclose(fout);
    return 0;
}
